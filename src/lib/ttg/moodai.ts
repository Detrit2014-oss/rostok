export function moodAnalyze(text: string): MoodAnalysis {
  const lower = text.toLowerCase();
  const tags: string[] = [];
  for (const [tag, words] of Object.entries(KEYWORDS)) {
    for (const w of words) {
      if (lower.includes(w)) {
        tags.push(tag);
        break;
      }
    }
  }

  let score = 0;
  if (tags.includes("радость")) score += 22;
  if (tags.includes("забота")) score += 12;
  if (tags.includes("стресс")) score -= 18;
  if (tags.includes("грусть")) score -= 18;
  if (tags.includes("злость")) score -= 15;
  if (tags.includes("усталость")) score -= 12;
  if (tags.includes("экран")) score -= 8;

  const reply = buildReply(score, tags, text);
  return { score: Math.min(100, Math.max(-100, score)), tags, reply };
}

function buildReply(score: number, tags: string[], text: string): string {
  const b: string[] = [];
  if (score >= 40) {
    b.push("Звучит как хороший день — здорово, что вы заметили это и записали. ");
  } else if (score >= 10) {
    b.push("Спасибо, что поделились. День в целом звучит спокойно. ");
  } else if (score > -30) {
    b.push("Бывают такие дни. Вы молодец, что не остались с этим наедине. ");
  } else {
    b.push("Похоже, день выдался непростым. Сегодня будем бережны к себе. ");
  }

  if (tags.length === 0) {
    b.push(
      "Попробуйте маленькую вечернюю паузу: 10 минут без экрана, телефон — " +
        "в другой комнате. Такие микропаузы снижают фоновую тревогу лучше " +
        "многих других приёмов."
    );
    return b.join("");
  }

  const first = tags[0];
  b.push(`Кажется, тема дня — «${first}». `);
  const pool = RECOMMENDATIONS[first] ?? [];
  if (pool.length > 0) {
    b.push(pool[text.length % pool.length]);
  }
  if (tags.length > 1) {
    const second = RECOMMENDATIONS[tags[1]] ?? [];
    if (second.length > 0) {
      b.push(` И ещё: ${second[(text.length + 1) % second.length]}`);
    }
  }
  return b.join("");
}
