  static MoodAnalysis analyze(String text) {
    final String lower = text.toLowerCase();
    final List<String> tags = <String>[];
    _keywords.forEach((String tag, List<String> words) {
      for (final String w in words) {
        if (lower.contains(w)) {
          tags.add(tag);
          break;
        }
      }
    });

    int score = 0;
    if (tags.contains('радость')) score += 22;
    if (tags.contains('забота')) score += 12;
    if (tags.contains('стресс')) score -= 18;
    if (tags.contains('грусть')) score -= 18;
    if (tags.contains('злость')) score -= 15;
    if (tags.contains('усталость')) score -= 12;
    if (tags.contains('экран')) score -= 8;

    final String reply = _buildReply(score, tags, text);
    return MoodAnalysis(score.clamp(-100, 100).toInt(), tags, reply);
  }

  static String _buildReply(int score, List<String> tags, String text) {
    final StringBuffer b = StringBuffer();
    if (score >= 40) {
      b.write('Звучит как хороший день — здорово, что вы заметили это и записали. ');
    } else if (score >= 10) {
      b.write('Спасибо, что поделились. День в целом звучит спокойно. ');
    } else if (score > -30) {
      b.write('Бывают такие дни. Вы молодец, что не остались с этим наедине. ');
    } else {
      b.write('Похоже, день выдался непростым. Сегодня будем бережны к себе. ');
    }

    if (tags.isEmpty) {
      b.write(
          'Попробуйте маленькую вечернюю паузу: 10 минут без экрана, телефон — '
          'в другой комнате. Такие микропаузы снижают фоновую тревогу лучше '
          'многих других приёмов.');
      return b.toString();
    }

    final String first = tags.first;
    b.write('Кажется, тема дня — «$first». ');
    final List<String> pool = _recommendations[first] ?? const <String>[];
    if (pool.isNotEmpty) {
      b.write(pool[text.length % pool.length]);
    }
    if (tags.length > 1) {
      final List<String> second =
          _recommendations[tags[1]] ?? const <String>[];
      if (second.isNotEmpty) {
        b.write(' И ещё: ${second[(text.length + 1) % second.length]}');
      }
    }
    return b.toString();
  }
